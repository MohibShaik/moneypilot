package com.moneypilot.category;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import java.time.OffsetDateTime;
import java.util.UUID;
import org.hibernate.annotations.Generated;
import org.hibernate.generator.EventType;

/**
 * JPA entity mapped to the V2 {@code categories} table.
 *
 * <p>Follows the same conventions as the {@code users} entity: {@code id},
 * {@code created_at}, and {@code updated_at} are database-generated
 * ({@code insertable=false} + {@link Generated}) and read back after insert;
 * Hibernate runs with {@code ddl-auto=validate} so this mapping must match the
 * schema exactly.
 *
 * <p>{@code userId} is nullable: {@code null} means a system/default category
 * shared across all users; a non-null value means the category is owned by that
 * user.
 */
@Entity
@Table(name = "categories")
public class Category {

    @Id
    @Generated(event = EventType.INSERT)
    @Column(name = "id", columnDefinition = "uuid", nullable = false, updatable = false,
            insertable = false)
    private UUID id;

    /** Owner; {@code null} for a system/default category. */
    @Column(name = "user_id")
    private UUID userId;

    @Column(name = "name", nullable = false)
    private String name;

    @Enumerated(EnumType.STRING)
    @Column(name = "category_type", nullable = false, length = 20)
    private CategoryType categoryType;

    @Generated(event = EventType.INSERT)
    @Column(name = "created_at", nullable = false, insertable = false, updatable = false)
    private OffsetDateTime createdAt;

    @Generated(event = {EventType.INSERT, EventType.UPDATE})
    @Column(name = "updated_at", nullable = false, insertable = false, updatable = false)
    private OffsetDateTime updatedAt;

    protected Category() {
        // Required by JPA.
    }

    /**
     * Creates a user-owned category. The {@code id}, {@code created_at}, and
     * {@code updated_at} are generated by the database and populated after save.
     */
    public Category(UUID userId, String name, CategoryType categoryType) {
        this.userId = userId;
        this.name = name;
        this.categoryType = categoryType;
    }

    public UUID getId() {
        return id;
    }

    public UUID getUserId() {
        return userId;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public CategoryType getCategoryType() {
        return categoryType;
    }

    public void setCategoryType(CategoryType categoryType) {
        this.categoryType = categoryType;
    }

    public OffsetDateTime getCreatedAt() {
        return createdAt;
    }

    public OffsetDateTime getUpdatedAt() {
        return updatedAt;
    }

    /** Whether this is a system/default category (not owned by any user). */
    public boolean isSystem() {
        return userId == null;
    }
}
