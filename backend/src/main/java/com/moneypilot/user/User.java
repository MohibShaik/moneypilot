package com.moneypilot.user;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import java.time.OffsetDateTime;
import java.util.UUID;
import org.hibernate.annotations.Generated;
import org.hibernate.annotations.JdbcTypeCode;
import org.hibernate.generator.EventType;
import org.hibernate.type.SqlTypes;

/**
 * JPA entity mapped one-to-one to the existing V2 {@code users} table.
 *
 * <p>The database is the source of truth (Hibernate runs with
 * {@code ddl-auto=validate}); this mapping must match the V2 schema exactly and
 * never alters it.
 *
 * <p>Per the authentication LLD (section 4), the {@code id} UUID is generated by
 * the database using the {@code gen_random_uuid()} column default, not by the
 * application. {@code id} is therefore {@code insertable=false} and marked
 * {@link Generated} on INSERT, so Hibernate omits it from the INSERT, lets
 * PostgreSQL generate it, and reads the generated value back via the SQL
 * {@code returning} clause. {@code created_at} and {@code updated_at} are
 * likewise populated by their database defaults and read back the same way;
 * none of these three are written by the application.
 *
 * <p>Per the approved design, {@code currency} and {@code timezone} use ordinary
 * insertable/updatable mappings — the service always supplies concrete values
 * (defaulting to {@code INR} / {@code Asia/Kolkata} when omitted), while the
 * PostgreSQL column defaults remain as a database-level safety net.
 *
 * <p>{@code passwordHash} is confined to this entity and is never exposed
 * through any API DTO or response.
 */
@Entity
@Table(name = "users")
public class User {

    @Id
    @Generated(event = EventType.INSERT)
    @Column(name = "id", columnDefinition = "uuid", nullable = false, updatable = false,
            insertable = false)
    private UUID id;

    @Column(name = "email", nullable = false, unique = true)
    private String email;

    @Column(name = "display_name", nullable = false)
    private String displayName;

    @Column(name = "password_hash", nullable = false)
    private String passwordHash;

    // V2 column is CHAR(3) (PostgreSQL bpchar). @JdbcTypeCode(CHAR) makes
    // Hibernate expect Types.CHAR so ddl-auto=validate matches bpchar rather
    // than the default varchar mapping for String.
    @JdbcTypeCode(SqlTypes.CHAR)
    @Column(name = "currency", nullable = false, length = 3)
    private String currency;

    @Column(name = "timezone", nullable = false, length = 50)
    private String timezone;

    @Generated(event = EventType.INSERT)
    @Column(name = "created_at", nullable = false, insertable = false, updatable = false)
    private OffsetDateTime createdAt;

    @Generated(event = {EventType.INSERT, EventType.UPDATE})
    @Column(name = "updated_at", nullable = false, insertable = false, updatable = false)
    private OffsetDateTime updatedAt;

    protected User() {
        // Required by JPA.
    }

    /**
     * Creates a new user with the application-assigned fields. The {@code id},
     * {@code created_at}, and {@code updated_at} values are generated by the
     * database on insert and populated on the entity afterwards.
     */
    public User(String email, String displayName, String passwordHash,
                String currency, String timezone) {
        this.email = email;
        this.displayName = displayName;
        this.passwordHash = passwordHash;
        this.currency = currency;
        this.timezone = timezone;
    }

    public UUID getId() {
        return id;
    }

    public void setId(UUID id) {
        this.id = id;
    }

    public String getEmail() {
        return email;
    }

    public void setEmail(String email) {
        this.email = email;
    }

    public String getDisplayName() {
        return displayName;
    }

    public void setDisplayName(String displayName) {
        this.displayName = displayName;
    }

    public String getPasswordHash() {
        return passwordHash;
    }

    public void setPasswordHash(String passwordHash) {
        this.passwordHash = passwordHash;
    }

    public String getCurrency() {
        return currency;
    }

    public void setCurrency(String currency) {
        this.currency = currency;
    }

    public String getTimezone() {
        return timezone;
    }

    public void setTimezone(String timezone) {
        this.timezone = timezone;
    }

    public OffsetDateTime getCreatedAt() {
        return createdAt;
    }

    public OffsetDateTime getUpdatedAt() {
        return updatedAt;
    }
}
